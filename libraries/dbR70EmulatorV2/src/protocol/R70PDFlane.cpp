const MappingEntry* entries() {
  return kEntries;
}

size_t entryCount() {
  return sizeof(kEntries) / sizeof(kEntries[0]);
}

const MappingEntry* findMapping(const ObjectAddress& objectAddress) {
  for (size_t index = 0; index < entryCount(); ++index) {
    const MappingEntry& entry = kEntries[index];
    if (entry.channelNumber == objectAddress.channelNumber &&
        entry.boxNumber == objectAddress.boxNumber &&
        entry.objectNumber == objectAddress.objectNumber) {
      return &entry;
    }
  }
  return 0;
}

